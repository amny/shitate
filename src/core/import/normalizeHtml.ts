import { MERMAID_LANGUAGE } from '../diagram';

/** Number spans inserted by the export (design.md §7.1); never part of the document text. */
const RESOLVED_LABEL_SELECTOR = 'span.heading-number, span.caption-number';

/** Parts the export generates from meta / revisions / theme settings (design.md §6). */
const GENERATED_SECTION_SELECTOR =
  'section.doc-cover, section.doc-revisions, header.doc-header, footer.doc-footer';

/**
 * Mermaid diagrams drawn by the export (SVG only, without the source). Their labels would
 * otherwise become text; the source comes back from the embedded data instead (§6).
 */
const EXPORTED_DIAGRAM_SELECTOR = 'div.mermaid-diagram';

/**
 * Mermaid's own embedding (`<pre class="mermaid">source</pre>`, also as a div). Mermaid marks
 * an element it has already replaced with its SVG as `data-processed`; that has no source.
 */
const MERMAID_SOURCE_SELECTOR =
  'pre.mermaid:not([data-processed]), div.mermaid:not([data-processed])';

function moveChildren(from: Element, to: Element): Element {
  to.append(...from.childNodes);
  return to;
}

function tableCaption(document: Document, source: Element): Element {
  const caption = document.createElement('div');
  caption.className = 'table-caption';
  return moveChildren(source, caption);
}

/** Wraps `table` (in place) as `div.table-figure > caption + table`. */
function wrapAsTableFigure(document: Document, caption: Element, table: Element): void {
  const wrapper = document.createElement('div');
  wrapper.className = 'table-figure';
  table.before(wrapper);
  wrapper.append(caption, table);
}

/** `<pre><code class="language-mermaid">source</code></pre>`, which the codeBlock parses. */
function mermaidCodeBlock(document: Document, source: string): Element {
  const pre = document.createElement('pre');
  const code = document.createElement('code');
  code.className = `language-${MERMAID_LANGUAGE}`;
  code.textContent = source;
  pre.append(code);
  return pre;
}

/**
 * Prepares external / pasted HTML for parsing (design.md §6):
 * - removes numbers inserted by the export, so they do not become text;
 * - removes the header, footer, cover and revision history generated by the export, and the
 *   SVG of its Mermaid diagrams;
 * - turns Mermaid's `pre.mermaid` / `div.mermaid` into Mermaid code blocks (§5.9);
 * - rewrites table captions into `div.table-figure > div.table-caption + table`,
 *   because one element cannot be parsed into two nodes (tableFigure and table).
 */
export function normalizeImportedHtml(html: string): string {
  const document = new DOMParser().parseFromString(`<body>${html}</body>`, 'text/html');
  const { body } = document;

  for (const label of body.querySelectorAll(RESOLVED_LABEL_SELECTOR)) {
    label.remove();
  }
  for (const section of body.querySelectorAll(GENERATED_SECTION_SELECTOR)) {
    section.remove();
  }
  for (const diagram of body.querySelectorAll(EXPORTED_DIAGRAM_SELECTOR)) {
    diagram.remove();
  }
  for (const element of body.querySelectorAll(MERMAID_SOURCE_SELECTOR)) {
    element.replaceWith(mermaidCodeBlock(document, element.textContent.trim()));
  }

  // <figure><table>…</table><figcaption>…</figcaption></figure>
  for (const figure of body.querySelectorAll('figure')) {
    const table = figure.querySelector(':scope > table');
    if (!table) continue;
    const figcaption = figure.querySelector(':scope > figcaption');
    const caption = tableCaption(document, figcaption ?? document.createElement('div'));
    figure.before(table);
    wrapAsTableFigure(document, caption, table);
    figure.remove();
  }

  // <table><caption>…</caption>…</table> (not already inside a table figure)
  for (const caption of body.querySelectorAll('table > caption')) {
    const table = caption.parentElement;
    caption.remove();
    if (table && !table.parentElement?.classList.contains('table-figure')) {
      wrapAsTableFigure(document, tableCaption(document, caption), table);
    }
  }

  return body.innerHTML;
}
